CREATE TABLE IF NOT EXISTS analytics_events (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_name varchar(80) NOT NULL,
    actor_user_id uuid REFERENCES users(id) ON DELETE SET NULL,
    actor_role varchar(32),
    entity_type varchar(64),
    entity_id varchar(64),
    session_id varchar(128),
    properties jsonb NOT NULL DEFAULT '{}'::jsonb,
    created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS analytics_events_name_created_idx ON analytics_events (event_name, created_at);
CREATE INDEX IF NOT EXISTS analytics_events_actor_idx ON analytics_events (actor_user_id, created_at);
CREATE INDEX IF NOT EXISTS analytics_events_session_idx ON analytics_events (session_id, created_at);

ALTER TABLE analytics_events ENABLE ROW LEVEL SECURITY;
